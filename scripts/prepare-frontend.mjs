/**
 * Stages an isolated copy of the frontend for QA builds.
 *
 * WHY A COPY AND NOT AN IN-PLACE BUILD
 * ------------------------------------
 * Next.js can only relocate its build output via `distDir` in next.config.*,
 * and CONFIG_FILES in next/dist/shared/lib/constants.js hardcodes config
 * resolution to the project root. There is no --distDir or --config CLI flag
 * (verified against next@16.3.0). Relocating .next would therefore require
 * editing crm_frontend/next.config.mjs, which the zero-app-changes rule
 * forbids. Both `next dev` and `next build` also share the same .next, so
 * building in place while a dev server is running risks corrupting it.
 *
 * Staging into .qa-build/frontend gives the QA build its own .next, leaving
 * crm_frontend/.next completely untouched.
 *
 * WHAT IS COPIED
 *   - everything except node_modules, .next, .git and .env*
 *   - node_modules is CLONED from the real frontend rather than installed
 *     afresh, so dependency versions match the app exactly
 *   - .env* is excluded deliberately: QA writes its own .env.local so config
 *     is explicit rather than inherited
 *
 * Why clone node_modules instead of symlinking it: Turbopack refuses a symlink
 * that resolves outside the project root ("Symlink ... points out of the
 * filesystem root"), which rules out the cheaper approach. On APFS, `cp -Rc`
 * uses clonefile so the 526MB tree shares blocks with the original and costs
 * almost no additional disk. The clone is cached and only repeats when the
 * frontend's package-lock.json changes.
 *
 * This is also the seam Phase 6 will reuse: QA_ISOLATED_WORKSPACE=1 only needs
 * to change the copy SOURCE from "sibling working copy" to "git worktree at a
 * pinned ref". Nothing downstream changes.
 */

import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { qaEnv } from "../config/env.ts";

const EXCLUDES = [
  "node_modules",
  ".next",
  ".git",
  ".env*",
  ".DS_Store",
  ".qa-build",
  // QA-owned files that live in the staged copy and must survive --delete,
  // since they do not exist in the source.
  ".qa-node-modules-stamp",
];

function rsync(source, destination) {
  const args = ["-a", "--delete"];
  for (const pattern of EXCLUDES) {
    args.push(`--exclude=${pattern}`);
  }
  // Trailing slash on the source copies contents, not the directory itself.
  args.push(`${source}/`, `${destination}/`);
  execFileSync("rsync", args, { stdio: "inherit" });
}

/** Fingerprint of the frontend's dependency set, used to cache the clone. */
function dependencyFingerprint(realFrontend) {
  const hash = crypto.createHash("sha256");
  for (const name of ["package.json", "package-lock.json"]) {
    const file = path.join(realFrontend, name);
    if (fs.existsSync(file)) hash.update(fs.readFileSync(file));
  }
  return hash.digest("hex");
}

function syncNodeModules(realFrontend, staged) {
  const source = path.join(realFrontend, "node_modules");
  if (!fs.existsSync(source)) {
    throw new Error(
      `${source} does not exist. Run "npm install" in crm_frontend first - ` +
        `QA clones its dependencies rather than installing a second copy.`,
    );
  }

  const destination = path.join(staged, "node_modules");
  const stampPath = path.join(staged, ".qa-node-modules-stamp");
  const fingerprint = dependencyFingerprint(realFrontend);

  if (fs.existsSync(destination) && fs.existsSync(stampPath)) {
    if (fs.readFileSync(stampPath, "utf8").trim() === fingerprint) {
      return "cached (dependencies unchanged)";
    }
  }

  fs.rmSync(destination, { recursive: true, force: true });

  // -c requests APFS clonefile: copy-on-write, so this shares blocks with the
  // original instead of duplicating 526MB. Falls back to a plain recursive
  // copy on filesystems that do not support cloning.
  try {
    execFileSync("cp", ["-Rc", source, destination], { stdio: "inherit" });
  } catch {
    execFileSync("cp", ["-R", source, destination], { stdio: "inherit" });
  }

  fs.writeFileSync(stampPath, fingerprint + "\n", "utf8");
  return "cloned";
}

/**
 * Writes the QA .env.local into the staged copy.
 *
 * NEXT_PUBLIC_API_BASE_URL must stay "/api": it is inlined at build time, but
 * being origin-relative it works on any port, and it keeps the auth cookie
 * same-origin with the frontend. API_INTERNAL_BASE_URL is read at runtime by
 * next.config.mjs rewrites(), so it points the proxy at the QA backend.
 *
 * Contains no secrets - only URLs.
 */
function writeStagedEnv(staged) {
  const contents = [
    "# Generated by crm_qa scripts/prepare-frontend.mjs - do not edit by hand.",
    "# Same-origin proxy: the browser calls /api/* on the frontend origin and",
    "# next.config.mjs rewrites() forwards to API_INTERNAL_BASE_URL.",
    "NEXT_PUBLIC_API_BASE_URL=/api",
    `API_INTERNAL_BASE_URL=${qaEnv.backendUrl}`,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(staged, ".env.local"), contents, "utf8");
}

function gitDescribe(repoPath) {
  const run = (args) => {
    try {
      return execFileSync("git", ["-C", repoPath, ...args], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
    } catch {
      return null;
    }
  };
  return {
    sha: run(["rev-parse", "HEAD"]),
    branch: run(["rev-parse", "--abbrev-ref", "HEAD"]),
    dirty: run(["status", "--porcelain"]) !== "",
  };
}

export function prepareFrontend() {
  const source = qaEnv.frontendPath;
  const staged = qaEnv.stagedFrontendPath;

  console.log("\n[qa-prepare] staging an isolated frontend copy");
  console.log(`[qa-prepare]   from : ${source}`);
  console.log(`[qa-prepare]   to   : ${staged}`);

  const info = gitDescribe(source);
  console.log(
    `[qa-prepare]   ref  : ${info.branch ?? "?"} @ ${info.sha?.slice(0, 8) ?? "?"}` +
      `${info.dirty ? " (working tree dirty)" : ""}`,
  );

  fs.mkdirSync(staged, { recursive: true });
  rsync(source, staged);

  const moduleState = syncNodeModules(source, staged);
  console.log(`[qa-prepare]   node_modules: ${moduleState}`);

  writeStagedEnv(staged);
  console.log(`[qa-prepare]   wrote .env.local -> API_INTERNAL_BASE_URL=${qaEnv.backendUrl}`);

  // Prove the real frontend's build output was not involved.
  const realNext = path.join(source, ".next");
  if (fs.existsSync(realNext)) {
    const buildIdPath = path.join(realNext, "BUILD_ID");
    const buildId = fs.existsSync(buildIdPath)
      ? fs.readFileSync(buildIdPath, "utf8").trim()
      : "(none)";
    console.log(`[qa-prepare]   crm_frontend/.next untouched (BUILD_ID ${buildId})`);
  }

  return { staged, source, git: info };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  prepareFrontend();
  console.log("[qa-prepare] done\n");
}
